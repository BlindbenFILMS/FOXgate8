export const defaults = fam => Object.fromEntries((ENEMIES[fam] ? ENEMIES[fam].params : []).map(p => [p.k, p.def]));
export function loadTune() { let s = {}; try { s = JSON.parse(localStorage.getItem(KEY)) || {}; } catch (e) {} const out = {}; for (const f in ENEMIES) out[f] = { ...defaults(f), ...(s[f] || {}) }; return out; }
export function saveTune(fam, vals) { let s = {}; try { s = JSON.parse(localStorage.getItem(KEY)) || {}; } catch (e) {} s[fam] = vals; try { localStorage.setItem(KEY, JSON.stringify(s)); } catch (e) {} }
